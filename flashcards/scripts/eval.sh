#!/usr/bin/env bash
#
# eval.sh — manual evaluation harness for POST /quiz/generate.
#
# Runs a fixed set of scenarios against a running local server and
# accumulates the results into scripts/eval-output.md for manual review.
# Each scenario records a semantic description of the input (not the raw
# curl command) followed by the actual, pretty-printed JSON response.
#
# Usage:
#   ./scripts/eval.sh
#
# Requires the server to already be running (default: http://localhost:8080)
# and `jq` to be installed.

set -euo pipefail

BASE_URL="${BASE_URL:-http://localhost:8080}"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUTPUT_FILE="${SCRIPT_DIR}/eval-output.md"
SCENARIO_COUNT=0

if ! command -v jq >/dev/null 2>&1; then
  echo "Error: jq is required but was not found on PATH." >&2
  exit 1
fi

if ! curl -s -o /dev/null -m 5 "${BASE_URL}/health"; then
  echo "Error: could not reach ${BASE_URL}/health. Is the server running?" >&2
  exit 1
fi

: > "${OUTPUT_FILE}"
{
  echo "# Quiz Endpoint Eval Results"
  echo
  echo "Generated by scripts/eval.sh against ${BASE_URL} on $(date -u +"%Y-%m-%dT%H:%M:%SZ")."
  echo
} >> "${OUTPUT_FILE}"

# run_scenario <title> <description> <request_json>
#
# POSTs <request_json> to /quiz/generate and appends a markdown section with
# the scenario title, its semantic description, and the pretty-printed JSON
# response to OUTPUT_FILE. Stores the raw response in LAST_RESPONSE so
# callers can inspect it (e.g. to extract a conversationId) without needing
# command substitution, which would run this function in a subshell and
# lose the SCENARIO_COUNT increment.
LAST_RESPONSE=""
run_scenario() {
  local title="$1"
  local description="$2"
  local request_json="$3"

  SCENARIO_COUNT=$((SCENARIO_COUNT + 1))

  local response
  response="$(curl -s -X POST "${BASE_URL}/quiz/generate" \
    -H "Content-Type: application/json" \
    -d "${request_json}")"
  LAST_RESPONSE="${response}"

  local pretty
  if pretty="$(echo "${response}" | jq '.' 2>/dev/null)"; then
    :
  else
    pretty="${response}"
  fi

  {
    echo "## ${SCENARIO_COUNT}. ${title}"
    echo
    echo "### Input"
    echo
    echo "${description}"
    echo
    echo "### Output"
    echo
    echo '```json'
    echo "${pretty}"
    echo '```'
    echo
  } >> "${OUTPUT_FILE}"
}

echo "Running quiz eval scenarios against ${BASE_URL}..."

# Scenario 1: new conversation (empty messages) — also used to bootstrap a
# real conversationId reused by later "continuing conversation" scenarios.
run_scenario \
  "New conversation" \
  "Starting a brand-new quiz conversation with an empty messages array. Captures the baseline first question the AI asks." \
  '{"messages": []}'

conversation_id="$(echo "${LAST_RESPONSE}" | jq -r '.conversationId // empty')"

if [ -z "${conversation_id}" ]; then
  echo "Warning: could not extract conversationId from scenario 1 response; later scenarios will use a placeholder id and are expected to fail validation." >&2
  conversation_id="MISSING_CONVERSATION_ID"
fi

# Scenario 2: correct answer.
run_scenario \
  "Correct answer" \
  "Continuing the conversation: the assistant asked a factual question and the user replies with the correct answer." \
  "$(jq -n --arg cid "${conversation_id}" '{
    conversationId: $cid,
    messages: [
      {role: "assistant", content: "What year did the Kingdom of England merge with the Kingdom of Scotland to form Great Britain?"},
      {role: "user", content: "1707"}
    ]
  }')"

# Scenario 3: incorrect answer.
run_scenario \
  "Incorrect answer" \
  "Continuing the conversation: the assistant asked a factual question and the user replies with a clearly wrong answer." \
  "$(jq -n --arg cid "${conversation_id}" '{
    conversationId: $cid,
    messages: [
      {role: "assistant", content: "Who defeated Richard III at the Battle of Bosworth Field in 1485?"},
      {role: "user", content: "Napoleon Bonaparte"}
    ]
  }')"

# Scenario 4: off-topic.
run_scenario \
  "Off-topic" \
  "Continuing the conversation: instead of answering the quiz question, the user asks something completely unrelated, to see if/how the assistant redirects back to the quiz." \
  "$(jq -n --arg cid "${conversation_id}" '{
    conversationId: $cid,
    messages: [
      {role: "assistant", content: "What document did King John sign in 1215 at Runnymede?"},
      {role: "user", content: "By the way, what is the weather like today?"}
    ]
  }')"

# Scenario 5: correct answer, paraphrased.
run_scenario \
  "Correct but paraphrased answer" \
  "Continuing the conversation: the user gives a correct answer but phrases it very differently from the expected wording, to check the assistant isn't overly literal." \
  "$(jq -n --arg cid "${conversation_id}" '{
    conversationId: $cid,
    messages: [
      {role: "assistant", content: "What was the name of the war fought between the houses of Lancaster and York for the English throne?"},
      {role: "user", content: "It was that long conflict between two rival royal families, symbolized by flowers, one red one white"}
    ]
  }')"

# Scenario 6: user asks for a hint.
run_scenario \
  "User asks for a hint" \
  "Continuing the conversation: instead of answering, the user asks the assistant for a hint." \
  "$(jq -n --arg cid "${conversation_id}" '{
    conversationId: $cid,
    messages: [
      {role: "assistant", content: "Which king signed the Magna Carta in 1215?"},
      {role: "user", content: "I have no idea, can you give me a hint?"}
    ]
  }')"

# Scenario 7: rude/dismissive answer.
run_scenario \
  "Rude/dismissive answer" \
  "Continuing the conversation: the user responds dismissively/rudely instead of engaging with the question, to test tone handling." \
  "$(jq -n --arg cid "${conversation_id}" '{
    conversationId: $cid,
    messages: [
      {role: "assistant", content: "What event in 1066 led to the Norman Conquest of England?"},
      {role: "user", content: "This quiz is dumb, I do not care."}
    ]
  }')"

# Scenario 8: unknown conversationId (error case).
run_scenario \
  "Unknown conversationId (error case)" \
  "Sends a conversationId that was never issued by the server, alongside a non-empty messages array. Expects the existing 400 validation error." \
  '{
    "conversationId": "this-id-was-never-issued",
    "messages": [
      {"role": "assistant", "content": "What year did Athelstan unify the Kingdom of England?"},
      {"role": "user", "content": "927"}
    ]
  }'

# Scenario 9: malformed request body (error case).
run_scenario \
  "Malformed request body (error case)" \
  "Sends a deliberately malformed (non-JSON) request body. Expects the existing 400 Invalid JSON payload error." \
  'this is not valid json'

# Scenario 10: long multi-turn history.
run_scenario \
  "Long multi-turn history" \
  "Continuing the conversation with an extended history of 3+ prior question/answer exchanges, to see how the assistant behaves with a longer context window." \
  "$(jq -n --arg cid "${conversation_id}" '{
    conversationId: $cid,
    messages: [
      {role: "assistant", content: "Who was the first King of the English?"},
      {role: "user", content: "Athelstan"},
      {role: "assistant", content: "What survey did William the Conqueror commission in 1086?"},
      {role: "user", content: "The Domesday Book"},
      {role: "assistant", content: "What conflict lasted from 1337 to 1453 between England and France?"},
      {role: "user", content: "The Hundred Years War"}
    ]
  }')"

echo "Wrote ${SCENARIO_COUNT} scenario results to ${OUTPUT_FILE}"
